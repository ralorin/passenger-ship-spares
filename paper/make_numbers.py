"""
Generate numbers.tex and tables/tab_stock.tex from the analytical result files
of Sections IV and V (quadrature check, zone totals, stock vectors), so that no
number is typed by hand and every one carries a provenance tag in
numbers_manifest.csv. The values of the later experiments are written by
make_numbers_v2.py under the same rule.

Provenance tags:
  ANALYTIC   exact calculation or numerical quadrature, no data
  SIM        simulation under assumed parameters

    python make_numbers.py
"""
import csv
import json
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
TAB = os.path.join(HERE, "tables")
os.makedirs(TAB, exist_ok=True)

MACROS, MANIFEST = [], []
WORD = {1: "One", 2: "Two", 4: "Four", 8: "Eight"}


def put(name, value, tag, source, note=""):
    MACROS.append((name, value))
    MANIFEST.append(dict(macro=name, value=value, provenance=tag,
                         source=source, note=note))


def pct(x, d=1):
    return f"{100 * float(x):.{d}f}"


def sci(x):
    m, e = f"{x:.0e}".split("e")
    return f"{m}\\times 10^{{{int(e)}}}"


# ---------------------------------------------------------------- quadrature
T = json.load(open(os.path.join(DATA, "theory_cover.json")))
src = "analysis/theory_cover.py -> data/theory_cover.json"
q = T["quadrature"]
put("quadGrid", sci(q["max_abs_change_grid"]), "ANALYTIC", src, "stability of the Simpson grid")
put("quadNodes", str(int(q["grid_nodes"])), "ANALYTIC", src)
put("quadGH", pct(q["max_abs_error_gauss_hermite60"], 1), "ANALYTIC", src,
    "error of 60-node Gauss-Hermite, percentage points")

# ---------------------------------------------------------------- zone totals
M = json.load(open(os.path.join(DATA, "multiproduct.json")))
src = "analysis/multiproduct.py -> data/multiproduct.json"
P = pd.DataFrame(M["plans"])
X = pd.DataFrame(M["cross"])
SHIP, INTER = "A: ship-wide only", "B: interaction only"
put("mpSigma", f"{M['sigma']:.1f}", "ANALYTIC", src, "assumed total latent sd")
put("mpMean", f"{M['total_mean']:.0f}", "ANALYTIC", src, "assumed expected failures")
put("mpTrunc", sci(M["max_truncation"]), "ANALYTIC", src)


def q99(Pn, structure):
    return int(P[(P.P == Pn) & (P.structure == structure)].q99.iloc[0])


for Pn in (1, 4, 8):
    put(f"mpShip{WORD[Pn]}", str(q99(Pn, SHIP)), "ANALYTIC", src)
    put(f"mpInter{WORD[Pn]}", str(q99(Pn, INTER)), "ANALYTIC", src)
r = X[(X.P == 8) & (X.planned_under == INTER) & (X.truth == SHIP)]
put("mpWrongCover", pct(r.delivered.iloc[0], 1), "ANALYTIC", src,
    "plan assuming interaction only, truth ship-wide, 8 references")
r = X[(X.P == 8) & (X.planned_under == SHIP) & (X.truth == INTER)]
put("mpConsCover", pct(r.delivered.iloc[0], 3), "ANALYTIC", src)

# ---------------------------------------------------------------- stock vector
V = json.load(open(os.path.join(DATA, "stock_vector.json")))
src = "analysis/stock_vector.py -> data/stock_vector.json"
S = pd.DataFrame(V["rows"])
S = S[S.level == 99]


def sv(Pn, structure, col):
    return S[(S.P == Pn) & (S.structure == structure)][col].iloc[0]


put("svJointEight", str(int(sv(8, "ship-wide", "s_joint"))), "ANALYTIC", src,
    "per-reference stock, joint criterion, ship-wide")
put("svJointTotEight", str(int(sv(8, "ship-wide", "total_joint"))), "ANALYTIC", src)
put("svMargTotEight", str(int(sv(8, "ship-wide", "total_marginal"))), "ANALYTIC", src)
# joint cover actually delivered by per-reference marginal quantiles
put("svNaiveShip", pct(sv(8, "ship-wide", "joint_cover_of_marginal_plan")), "ANALYTIC", src,
    "P=8, ship-wide")
put("svNaiveInter", pct(sv(8, "interaction", "joint_cover_of_marginal_plan")), "ANALYTIC", src,
    "P=8, interaction")
put("svNaiveShipFour", pct(sv(4, "ship-wide", "joint_cover_of_marginal_plan")), "ANALYTIC", src)
# the joint criterion needs no more stock under a shared deviation
put("svJointShipTwo", str(int(sv(2, "ship-wide", "s_joint"))), "ANALYTIC", src)
put("svJointInterTwo", str(int(sv(2, "interaction", "s_joint"))), "ANALYTIC", src)

lines = []
for Pn in (2, 4, 8):
    for st, key in (("ship-wide", SHIP), ("interaction", INTER)):
        r = S[(S.P == Pn) & (S.structure == st)].iloc[0]
        lines.append(f"{Pn} & {st} & {int(r.s_marginal)} & "
                     f"{pct(r.joint_cover_of_marginal_plan)} & "
                     f"{int(r.s_joint)} & {int(r.total_joint)} & {q99(Pn, key)} \\\\")
with open(os.path.join(TAB, "tab_stock.tex"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

# ---------------------------------------------------------------- emit
with open(os.path.join(HERE, "numbers.tex"), "w", encoding="utf-8") as f:
    f.write("% Generated by make_numbers.py -- do not edit by hand.\n")
    for n, v in MACROS:
        f.write(f"\\newcommand{{\\{n}}}{{{v}}}\n")
with open(os.path.join(HERE, "numbers_manifest.csv"), "w", newline="", encoding="utf-8") as f:
    wr = csv.DictWriter(f, fieldnames=["macro", "value", "provenance", "source", "note"])
    wr.writeheader()
    wr.writerows(MANIFEST)
print(f"{len(MACROS)} macros written to numbers.tex")
